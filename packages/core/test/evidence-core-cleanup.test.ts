import {test} from "node:test";
import assert from "node:assert/strict";
import {mkdtempSync,writeFileSync,readdirSync,rmSync,existsSync,symlinkSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {attachCoreStream,releaseCoreStream} from "../src/evidence-core-stream.ts";
import {cleanupStaleCoreStreams,CORE_STREAM_STALE_MS} from "../src/evidence-core-cleanup.ts";
import type {AnalysisBatch} from "@cie/schema";
test("stale stream cleanup preserves live claims, unknown owners and symlinks",{skip:process.platform!=="linux"},t=>{
  const root=mkdtempSync(join(tmpdir(),"cie-cleanup-test-"));t.after(()=>rmSync(root,{recursive:true,force:true}));
  const future=Date.now()+CORE_STREAM_STALE_MS+1000;
  const batch={revision:"r",repoRoot:root,gitHead:null,analyzerVersion:"v",entities:[],facts:[],relationships:[],diagnostics:[]} as AnalysisBatch;
  const path=join(root,"cie-handle-2147483647-1.core.jsonl");writeFileSync(path,"metadata");
  attachCoreStream(batch,path);t.after(()=>releaseCoreStream(batch));
  assert.equal(cleanupStaleCoreStreams(root,future),0);assert.ok(existsSync(path));
  const ownLease=readdirSync(root).find(name=>name.includes(".lease-"))!;assert.ok(ownLease);
  releaseCoreStream(batch);assert.ok(!existsSync(path));assert.ok(!existsSync(join(root,ownLease)));
  const unknown=join(root,"cie-handle-2147483647-2.core.jsonl");writeFileSync(unknown,"unknown");
  const foreign=join(root,"cie-handle-2147483647-3.core.jsonl");writeFileSync(foreign,"foreign");writeFileSync(foreign+".lease-foreign-2147483647","");
  const target=join(root,"keep.txt");writeFileSync(target,"keep");symlinkSync(target,path);
  const deadLease=ownLease.replace(new RegExp(`-${process.pid}$`),"-2147483647");writeFileSync(join(root,deadLease),"");
  const liveWorker=`cie-handle-${process.pid}-4.core.jsonl`;
  writeFileSync(join(root,liveWorker),"worker still alive");
  writeFileSync(join(root,deadLease.replace("cie-handle-2147483647-1.core.jsonl",liveWorker)),"");
  const linkedClaim="cie-handle-2147483647-5.core.jsonl";writeFileSync(join(root,linkedClaim),"regular data");
  symlinkSync(target,join(root,deadLease.replace("cie-handle-2147483647-1.core.jsonl",linkedClaim)));
  assert.equal(cleanupStaleCoreStreams(root,future),0);
  assert.ok(existsSync(unknown));assert.ok(existsSync(foreign));assert.ok(existsSync(target));
  assert.ok(existsSync(join(root,liveWorker)));assert.ok(existsSync(join(root,linkedClaim)));
});
